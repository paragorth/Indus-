SUPPORTS = {'Tablet', 'Lames (short thin tablet)', '3-sided bar', '4-sided bar'}

# ------------------------------------------------------------------ corpora

def ctoks(doc):
    return [t for t in doc if t not in ('NL', 'DV')]


def tidy(doc):
    out = []
    for t in doc:
        if t == 'NL' and (not out or out[-1] == 'NL'): continue
        out.append(t)
    while out and out[-1] in ('NL', 'DV'): out.pop()
    while out and out[0] in ('NL', 'DV'): out.pop(0)
    return out


SITE = {}  # document text -> site prefix (used by the E_wordsite forger)


def load_la():
    c = json.load(open(os.path.join(D, 'corpus.json')))
    docs, ids = [], []
    for r in c:
        if r['support'] not in SUPPORTS: continue
        d = []
        for t in r['tokens']:
            if t['t'] == 'word': d.append('W:' + '-'.join(t['s']))
            elif t['t'] == 'logo': d.append('L:' + t['v'])
            elif t['t'] == 'num':
                if t['v'] > 0 or not t['frac']: d.append('N:%d' % t['v'])
                for f in t['frac']: d.append('F:' + f)
            elif t['t'] == 'nl': d.append('NL')
            elif t['t'] == 'div': d.append('DV')
        d = tidy(d)
        if len(ctoks(d)) >= 4:
            docs.append(d); ids.append(r['id']); SITE[' '.join(d)] = r['id'][:2]
    return docs, ids


LB_UNITS = set('TVZSMNPQ')


def _clean_lb(t):
    t = unicodedata.normalize('NFD', t)
    t = ''.join(ch for ch in t if unicodedata.category(ch) != 'Mn')
    t = re.sub(r"[\[\]⟦⟧⌞⌟⸢⸣'\"?!<>{}]", '', t)
    return t.strip('-')


def load_lb(n=285, seed=0):
    docs = []
    for line in open(os.path.join(D, 'damos_items.jsonl')):
        x = json.loads(line)
        if not x.get('content'): continue
        d = []
        for ln in x['content'].split('\n'):
            ln = ln.strip()
            if not ln: continue
            if d: d.append('NL')
            for raw in ln.split():
                if raw.startswith('.') or raw in (',', '/', '//', ':'): continue
                t = _clean_lb(raw)
                if not t or t.endswith('.') or '.' in t: continue
                if t.lower() in ('vacat', 'vac', 'lat', 'sup', 'inf', 'mut', 'vest', 'deest', 'fr',
                                 'supra', 'infra', 'sigillum', 'v', 'verso', 'recto', 'margo', 'textus'):
                    continue
                if any('Ͱ' <= ch <= 'Ͽ' for ch in t): continue
                if re.fullmatch(r'\d+', t): d.append('N:%s' % t); continue
                if t in LB_UNITS: d.append('F:' + t); continue
                if any(ch.islower() for ch in t):
                    if not re.fullmatch(r'[a-z0-9*\-]+', t): continue
                    s = [p for p in t.split('-') if p]
                    if not s: continue
                    d.append('W:' + '-'.join(s).upper()); continue
                if re.fullmatch(r"[A-Z*0-9;+±:]+", t): d.append('L:' + t); continue
        d = tidy(d)
        if len(ctoks(d)) >= 4 and any(t.startswith('W:') for t in d) and len(d) <= 120:
            docs.append(d); SITE[' '.join(d)] = x['heading'][:2]
    rng = random.Random(seed)
    rng.shuffle(docs)
    return docs[:n]


def plant_agreement(docs, seed=5):
    """PLA: the first sign of the first word fixes the first sign of the LAST word (a hidden key
    map from 'head sign' to 'tail sign'). Applies to every doc with >= 2 words."""
    rng = random.Random(seed)
    signs = sorted({s for d in docs for t in d if t.startswith('W:') for s in t[2:].split('-')})
    common = [s for s, _ in Counter(s for d in docs for t in d if t.startswith('W:')
                                    for s in t[2:].split('-')).most_common(40)]
    key = {s: rng.choice(common) for s in signs}
    out = []
    for d in docs:
        d = list(d)
        wi = [i for i, t in enumerate(d) if t.startswith('W:')]
        if len(wi) >= 2:
            h = d[wi[0]][2:].split('-')[0]
            last = d[wi[-1]][2:].split('-')
            last[0] = key[h]
            d[wi[-1]] = 'W:' + '-'.join(last)
        out.append(d)
    return out, key


# ------------------------------------------------------------------ sign stream

def to_stream(doc):
    s = []
    for t in doc:
        if t.startswith('W:'):
            s.extend('S:' + x for x in t[2:].split('-')); s.append('/')
        else: s.append(t)
    return s


def from_stream(s):
    d, cur = [], []
    for t in s:
        if t.startswith('S:'): cur.append(t[2:]); continue
        if cur: d.append('W:' + '-'.join(cur)); cur = []
        if t == '/': continue
        d.append(t)
    if cur: d.append('W:' + '-'.join(cur))
    return tidy(d)


