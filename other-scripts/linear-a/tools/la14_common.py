#!/usr/bin/env python3
"""LA-14 shared code: THE FORGERY CONTEST.

Do not model Linear A; forge it. Forgers of rising power are trained on one half of the real
documents (half A); discriminators try to tell the other half (half B) from forgeries under
5-fold cross-validation. What a discriminator still uses to catch the best forger is structure
that the forger's model class does not explain.

Document = list of word-level tokens:
  'W:KU-RO' word (sign string), 'L:GRA' logogram, 'N:197' integer, 'F:J' fraction letter,
  'NL' new line, 'DV' divider.
Sign stream (for sign-level forgers): words become 'S:KU','S:RO','/' .

Corpora: LA (tablets, lames, bars with >= 4 content tokens), LB (DAMOS, size-matched sample),
PLA (planted: real LA with an injected long-range agreement), FW_<forger> (a world generated by a
forger itself, the negative control).
"""
import json, math, os, random, re, unicodedata
from collections import Counter, defaultdict
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
D = os.path.join(HERE, '..', 'data')
OUT = os.path.join(D, 'la14')
