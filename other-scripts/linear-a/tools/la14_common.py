class Markov:
    """Order-k Markov chain with interpolated backoff (Witten-Bell-like) over a token stream."""
    def __init__(self, seqs, k):
        self.k = k
        self.c = [defaultdict(Counter) for _ in range(k + 1)]
        for s in seqs:
            s = ['<s>'] * k + list(s) + ['</s>']
            for i in range(k, len(s)):
                for j in range(k + 1):
                    self.c[j][tuple(s[i - j:i])][s[i]] += 1
        self.cache = {}

    def dist(self, ctx):
        key = tuple(ctx)
        if key in self.cache: return self.cache[key]
        p = Counter()
        for tok, n in self.c[0][()].items(): p[tok] = n
        tot = sum(p.values()); p = {t: v / tot for t, v in p.items()}
        for j in range(1, self.k + 1):
            cc = self.c[j].get(tuple(ctx[len(ctx) - j:]))
            if not cc: break
            n = sum(cc.values()); u = len(cc); lam = n / (n + u)
            p = {t: (1 - lam) * v for t, v in p.items()}
            for t, v in cc.items(): p[t] = p.get(t, 0) + lam * v / n
        toks = list(p); w = np.array([p[t] for t in toks]); w = w / w.sum()
        self.cache[key] = (toks, np.cumsum(w))
        return self.cache[key]

    def sample(self, rng, maxlen=150):
        ctx = ['<s>'] * self.k; out = []
        while len(out) < maxlen:
            toks, cw = self.dist(ctx[len(ctx) - self.k:] if self.k else [])
            t = toks[min(int(np.searchsorted(cw, rng.random())), len(toks) - 1)]
            if t == '</s>': break
            if t == '<s>': continue
            out.append(t); ctx.append(t)
        return out


def kind(t):
    if t.startswith('W:'): return 'W1' if '-' not in t else 'W2'
    if t in ('NL', 'DV'): return t
    return t[0]


class Unigram:
    def __init__(self, seqs):
        self.c = Counter(t for s in seqs for t in s); self.lens = [len(s) for s in seqs]
        self.toks = list(self.c); w = np.array([self.c[t] for t in self.toks], float)
        self.cw = np.cumsum(w / w.sum())

    def sample(self, rng):
        n = rng.choice(self.lens)
        return [self.toks[min(int(np.searchsorted(self.cw, rng.random())), len(self.toks) - 1)] for _ in range(n)]


class FlatGrammar:
    """Reimplementation of the la8 flat form: an order-2 chain over token kinds
    (W1, W2, L, N, F, NL, DV) with emissions drawn per kind; numbers drawn conditional on the
    kind of the previous token; words of novel type made by a sign-bigram chain at the
    training hapax rate."""
    def __init__(self, docs):
        self.kc = Markov([[kind(t) for t in d] for d in docs], 2)
        self.em = defaultdict(Counter); self.num = defaultdict(Counter)
        for d in docs:
            prev = '<s>'
            for t in d:
                k = kind(t)
                if k == 'N': self.num[prev][t] += 1
                else: self.em[k][t] += 1
                prev = k
        wc = Counter(t for d in docs for t in d if t.startswith('W:'))
        self.hapax = sum(1 for v in wc.values() if v == 1) / max(1, sum(wc.values()))
        self.sm = Markov([t[2:].split('-') for t in wc.elements()], 1)
        self._cum = {}

    def _draw(self, rng, cnt, key):
        if key not in self._cum:
            toks = list(cnt); w = np.array([cnt[t] for t in toks], float)
            self._cum[key] = (toks, np.cumsum(w / w.sum()))
        toks, cw = self._cum[key]
        return toks[min(int(np.searchsorted(cw, rng.random())), len(toks) - 1)]

    def sample(self, rng):
        ks = self.kc.sample(rng); out = []; prev = '<s>'
        for k in ks:
            if k == 'N':
                c = self.num.get(prev) or self.num['W2'] or Counter({'N:1': 1})
                out.append(self._draw(rng, c, 'N|' + prev))
            elif k in ('W1', 'W2') and rng.random() < self.hapax:
                for _ in range(20):
                    w = self.sm.sample(rng, 8)
                    if (k == 'W1') == (len(w) == 1) and w: break
                out.append('W:' + '-'.join(w) if w else self._draw(rng, self.em[k], k))
            elif k in ('NL', 'DV'): out.append(k)
            else:
                if not self.em[k]: continue
                out.append(self._draw(rng, self.em[k], k))
            prev = k
        return tidy(out)


class NeuralLM:
    """Small neural sequence model: a feed-forward neural LM (one hidden layer of 96 tanh units,
    window of 8 previous symbols, one-hot) over the sign stream, sampled autoregressively."""
    def __init__(self, docs, seed=0, win=8):
        from sklearn.neural_network import MLPClassifier
        from scipy import sparse
        self.win = win
        seqs = [to_stream(d) for d in docs]
        c = Counter(t for s in seqs for t in s)
        self.vocab = ['<pad>', '<s>', '</s>', '<unk>'] + sorted(t for t, n in c.items() if n >= 2)
        self.ix = {t: i for i, t in enumerate(self.vocab)}
        X, y = [], []
        for s in seqs:
            s2 = ['<s>'] + s + ['</s>']
            ids = [self.ix.get(t, 3) for t in s2]
            for i in range(1, len(ids)):
                ctx = ids[max(0, i - win):i]; ctx = [0] * (win - len(ctx)) + ctx
                X.append(ctx); y.append(ids[i])
        self.V = len(self.vocab)
        self.sp = sparse
        Xs = self._enc(np.array(X))
        self.m = MLPClassifier(hidden_layer_sizes=(96,), activation='tanh', alpha=1e-3,
                               max_iter=40, random_state=seed, early_stopping=False)
        self.m.fit(Xs, np.array(y))
        self.cls = self.m.classes_

    def _enc(self, X):
        n = X.shape[0]
        rows = np.repeat(np.arange(n), self.win)
        cols = (X + np.arange(self.win)[None, :] * self.V).ravel()
        return self.sp.csr_matrix((np.ones(len(cols)), (rows, cols)), shape=(n, self.win * self.V))

    def sample_many(self, rng, n, maxlen=150):
        ctxs = [[0] * (self.win - 1) + [1] for _ in range(n)]
        outs = [[] for _ in range(n)]; alive = list(range(n))
        pad_unk = {self.ix['<unk>'], 1, 0}
        for _ in range(maxlen):
            if not alive: break
            P = self.m.predict_proba(self._enc(np.array([ctxs[i][-self.win:] for i in alive])))
            nxt = []
            for row, i in zip(P, alive):
                p = row.copy()
                for j, cl in enumerate(self.cls):
                    if cl in pad_unk: p[j] = 0
                p /= p.sum()
                t = self.cls[min(int(np.searchsorted(np.cumsum(p), rng.random())), len(p) - 1)]
                if t == 2: continue
                outs[i].append(self.vocab[t]); ctxs[i].append(t); nxt.append(i)
            alive = nxt
        return [from_stream(o) for o in outs]


# ------------------------------------------------------------------ copy-edit forgers

def lines_of(d):
    L, cur = [], []
    for t in d:
        if t == 'NL': L.append(cur); cur = []
        else: cur.append(t)
    L.append(cur)
    return L


def join_lines(L):
    out = []
    for i, l in enumerate(L):
        if i: out.append('NL')
        out.extend(l)
    return tidy(out)


class CopyEdit:
    """Copies a real (half-A) document and applies one local edit of a given type."""
    TYPES = ['COPY0', 'E_num', 'E_numnear', 'E_word', 'E_logo', 'E_first', 'E_last', 'E_swapadj',
             'E_swapline', 'E_splice', 'E_numshuf', 'E_wordshuf', 'E_splLine', 'E_wordsite', 'E_splLM', 'E_splPair']

    def __init__(self, docs, etype):
        self.docs = docs; self.e = etype
        self.words = [t for d in docs for t in d if t.startswith('W:')]
        self.logos = [t for d in docs for t in d if t.startswith('L:')]
        self.nums = [t for d in docs for t in d if t.startswith('N:')]
        self.sitewords = defaultdict(list)
        for d in docs:
            st = SITE.get(' '.join(d), '??')
            self.sitewords[st] += [t for t in d if t.startswith('W:')]

    def ok(self, d):
        e = self.e
        if e in ('E_num', 'E_numnear'): return any(t.startswith('N:') for t in d)
        if e == 'E_numshuf': return len({t for t in d if t.startswith('N:')}) >= 2
        if e in ('E_word', 'E_first', 'E_last'): return any(t.startswith('W:') for t in d)
        if e == 'E_wordsite': return any(t.startswith('W:') for t in d) and len(self.sitewords.get(SITE.get(' '.join(d), '??'), [])) >= 30
        if e in ('E_splLine', 'E_splLM', 'E_splPair'): return len([l for l in lines_of(d) if l]) >= 3
        if e == 'E_wordshuf': return len({t for t in d if t.startswith('W:')}) >= 2
        if e == 'E_logo': return any(t.startswith('L:') for t in d)
        if e == 'E_swapline': return len([l for l in lines_of(d) if l]) >= 3
        if e == 'E_splice': return len(ctoks(d)) >= 6
        if e == 'E_swapadj': return len(ctoks(d)) >= 3
        return True

    def sample(self, rng):
        cand = [d for d in self.docs if self.ok(d)]
        if not getattr(self, 'queue', None):
            self.queue = list(range(len(self.docs))); rng.shuffle(self.queue)
            self.queue = [i for i in self.queue if self.ok(self.docs[i])]
            self.queue_all = list(self.queue)
        self.src = self.queue.pop()
        for _ in range(50):
            d = list(self.docs[self.src]); e = self.e
            if e == 'COPY0': return d
            if e in ('E_num', 'E_numnear'):
                i = rng.choice([i for i, t in enumerate(d) if t.startswith('N:')])
                v = int(d[i][2:])
                if e == 'E_num': nv = int(rng.choice(self.nums)[2:])
                else: nv = max(1, int(round(v * math.exp(rng.uniform(-0.7, 0.7)))) + rng.choice([-1, 1]) * (rng.random() < 0.3))
                if nv == v: continue
                d[i] = 'N:%d' % nv; return d
            if e in ('E_word', 'E_first', 'E_last'):
                wi = [i for i, t in enumerate(d) if t.startswith('W:')]
                i = wi[0] if e == 'E_first' else wi[-1] if e == 'E_last' else rng.choice(wi)
                w = rng.choice(self.words)
                if w == d[i]: continue
                d[i] = w; return d
            if e == 'E_wordsite':
                i = rng.choice([i for i, t in enumerate(d) if t.startswith('W:')])
                w = rng.choice(self.sitewords[SITE.get(' '.join(self.docs[self.src]), '??')])
                if w == d[i]: continue
                d[i] = w; return d
            if e == 'E_splLine':
                d2 = self.docs[rng.choice(self.queue_all)]
                if d2 == d: continue
                L1 = lines_of(d); L2 = lines_of(d2)
                i = rng.randint(1, len(L1) - 1); j = rng.randint(1, max(1, len(L2) - 1))
                return join_lines(L1[:i] + L2[j:])
            if e == 'E_splLM':  # line splice that keeps the line count of the first tablet exactly
                L1 = lines_of(d); n1 = len(L1); i = rng.randint(1, n1 - 1); need = n1 - i
                pool = [k for k in self.queue_all if k != self.src and len(lines_of(self.docs[k])) >= need + 1]
                if not pool: continue
                L2 = lines_of(self.docs[rng.choice(pool)])
                return join_lines(L1[:i] + L2[len(L2) - need:])
            if e == 'E_logo':
                i = rng.choice([i for i, t in enumerate(d) if t.startswith('L:')])
                w = rng.choice(self.logos)
                if w == d[i]: continue
                d[i] = w; return d
            if e == 'E_swapadj':
                ci = [i for i, t in enumerate(d) if t not in ('NL', 'DV')]
                j = rng.randrange(len(ci) - 1); a, b = ci[j], ci[j + 1]
                if d[a] == d[b]: continue
                d[a], d[b] = d[b], d[a]; return d
            if e == 'E_swapline':
                L = lines_of(d); idx = [i for i, l in enumerate(L) if l]
                a, b = rng.sample(idx, 2)
                if L[a] == L[b]: continue
                L[a], L[b] = L[b], L[a]; return join_lines(L)
            if e == 'E_splice':
                d2 = rng.choice(cand)
                if d2 == d: continue
                ca = len(d); cb = len(d2)
                i = rng.randint(ca // 3, max(ca // 3, 2 * ca // 3)); j = rng.randint(cb // 3, max(cb // 3, 2 * cb // 3))
                return tidy(d[:i] + d2[j:])
            if e in ('E_numshuf', 'E_wordshuf'):
                p = 'N:' if e == 'E_numshuf' else 'W:'
                ii = [i for i, t in enumerate(d) if t.startswith(p)]
                vals = [d[i] for i in ii]; v2 = vals[:]; rng.shuffle(v2)
                if v2 == vals: continue
                for i, v in zip(ii, v2): d[i] = v
                return d
        return list(self.docs[self.src])


GEN_FORGERS = ['UNI', 'MK1', 'MK2', 'MK3', 'MK4', 'WMK1', 'WMK2', 'FLAT', 'NEUR']


def make_forger(name, docs, seed=0):
    if name == 'UNI': return Unigram([to_stream(d) for d in docs]), 'stream'
    if name.startswith('MK'): return Markov([to_stream(d) for d in docs], int(name[2:])), 'stream'
    if name.startswith('WMK'): return Markov(docs, int(name[3:])), 'word'
    if name == 'FLAT': return FlatGrammar(docs), 'word'
    if name == 'NEUR': return NeuralLM(docs, seed=seed), 'neural'
    return CopyEdit(docs, name), 'word'


def forge(name, docs, n, seed):
    """Returns (forgeries, groups). Groups: identical forgeries share a group; copy-edit forgeries
    carry their source document, so CV never splits a source between train and test."""
    rng = random.Random(seed * 7919 + sum(map(ord, name)) * 31)
    f, mode = make_forger(name, docs, seed)
    out, grp = [], []
    if mode == 'neural':
        nrng = np.random.RandomState(seed)
        class R:
            def random(self): return nrng.random_sample()
        while len(out) < n:
            out += [d for d in f.sample_many(R(), n) if len(ctoks(d)) >= 4]
        out = out[:n]
    elif name == 'E_splPair':
        # leak-free splice: tablets are paired without replacement; each pair (a, b) gives a-head + b-tail and
        # b-head + a-tail, each with the line count of its head tablet; both forgeries share one CV group
        q = [d for d in docs if f.ok(d)]; rng.shuffle(q)
        for p in range(0, len(q) - 1, 2):
            a, b = lines_of(q[p]), lines_of(q[p + 1]); na, nb = len(a), len(b)
            i = rng.randint(max(1, na - nb + 1), na - 1); j = rng.randint(max(1, nb - na + 1), nb - 1)
            out += [join_lines(a[:i] + b[nb - (na - i):]), join_lines(b[:j] + a[na - (nb - j):])]
            grp += ['pair%d' % p] * 2
        return out[:n], grp[:n]
    elif isinstance(f, CopyEdit):
        nmax = sum(1 for d in docs if f.ok(d)); n = min(n, nmax)
        for _ in range(n):
            out.append(f.sample(rng)); grp.append('src%d' % f.src)
        return out, grp
    else:
        tries = 0
        while len(out) < n and tries < n * 50:
            tries += 1
            s = f.sample(rng)
            d = from_stream(s) if mode == 'stream' else tidy(s)
            if len(ctoks(d)) >= 4: out.append(d)
    seen = {}
    for d in out: grp.append('g%d' % seen.setdefault(' '.join(d), len(seen)))
    return out, grp


def real_for(name, B):
    """Real half-B documents eligible for the forger (copy-edit forgers need an editable slot)."""
    if name in CopyEdit.TYPES:
        ce = CopyEdit(B, name); return [d for d in B if ce.ok(d)]
    return B


