def nb(v):
    return 'n%d' % v if v <= 10 else 'n2^%d' % int(math.log2(v))


def ab(t):
    return nb(int(t[2:])) if t.startswith('N:') else t


def cls(t):
    if t.startswith('W:'): return 'W'
    return t if t in ('NL', 'DV') else t[0]


def _nums(d):
    return [int(t[2:]) for t in d if t.startswith('N:')]


def f_len(d):
    c = ctoks(d); L = [l for l in lines_of(d) if l]; ll = [len(l) for l in L] or [0]
    k = Counter(cls(t) for t in d)
    W = [t for t in d if t.startswith('W:')]
    return {'ntok': math.log1p(len(c)), 'nlines': math.log1p(len(L)), 'llmean': np.mean(ll), 'llsd': np.std(ll),
            'llmax': max(ll), 'fW': k['W'] / len(c), 'fL': k['L'] / len(c), 'fN': k['N'] / len(c),
            'fF': k['F'] / len(c), 'fDV': k['DV'] / len(c),
            'w1': sum('-' not in w for w in W) / max(1, len(W)),
            'wlen': np.mean([w.count('-') + 1 for w in W]) if W else 0}


def f_uni(d):
    return dict(Counter('u=' + ab(t) for t in ctoks(d)))


def f_sign(d):
    c = Counter()
    for t in d:
        if t.startswith('W:'):
            s = t[2:].split('-'); c['wl=%d' % min(len(s), 6)] += 1
            for x in s: c['s=' + x] += 1
    return dict(c)


def f_sbig(d):
    c = Counter()
    for t in d:
        if t.startswith('W:'):
            s = t[2:].split('-'); c['i=' + s[0]] += 1; c['f=' + s[-1]] += 1
            for a, b in zip(s, s[1:]): c['b=%s_%s' % (a, b)] += 1
    return dict(c)


def f_tbig(d):
    c = Counter(); a = [ab(t) for t in d]; k = [cls(t) for t in d]
    for i in range(len(d) - 1):
        c['tb=%s_%s' % (a[i], a[i + 1])] += 1; c['cb=%s_%s' % (k[i], k[i + 1])] += 1
    for i in range(len(d) - 2): c['ct=%s_%s_%s' % tuple(k[i:i + 3])] += 1
    return dict(c)


def f_pos(d):
    c = ctoks(d); L = [l for l in lines_of(d) if l]
    r = {'p0=' + ab(c[0]): 1, 'p1=' + ab(c[1]): 1, 'pE=' + ab(c[-1]): 1, 'pE2=' + ab(c[-2]): 1,
         'fl=' + '_'.join(cls(t) for t in L[0])[:20]: 1, 'll=' + '_'.join(cls(t) for t in L[-1])[:20]: 1}
    n = len(c)
    for i, t in enumerate(c):
        k = 'pc%d=%s' % (min(2, 3 * i // n), cls(t)); r[k] = r.get(k, 0) + 1
    for i, l in enumerate(L):
        if l and l[0].startswith('W:'):
            k = 'lw%d=%s' % (0 if i == 0 else 2 if i == len(L) - 1 else 1, l[0]); r[k] = r.get(k, 0) + 1
    return r


def f_arith(d):
    v = _nums(d); r = {}
    if not v: return {'nonum': 1}
    s = sum(v); n = len(v)
    r['tot_last'] = float(n >= 3 and v[-1] == sum(v[:-1]))
    r['tot_all'] = float(n >= 3 and any(2 * x == s for x in v))
    run = 0
    for i in range(2, n):
        for j in range(0, i - 1):
            if sum(v[j:i]) == v[i]: run += 1; break
    r['tot_run'] = run / n
    r['max_last'] = float(v[-1] == max(v) and n >= 2)
    r['maxshare'] = max(v) / s if s else 0
    r['distinct'] = len(set(v)) / n
    r['ones'] = v.count(1) / n
    r['round10'] = sum(x % 10 == 0 and x > 0 for x in v) / n
    lv = [math.log1p(x) for x in v]
    r['lmean'] = np.mean(lv); r['lsd'] = np.std(lv)
    r['desc'] = sum(b <= a for a, b in zip(v, v[1:])) / max(1, n - 1)
    r['near_last'] = float(n >= 3 and abs(v[-1] - sum(v[:-1])) <= max(1, 0.05 * v[-1]))
    return r


def f_numw(d):
    r = Counter(); prs = []
    for a, b in zip(d, d[1:]):
        if b.startswith('N:'):
            v = int(b[2:]); r['nw=%s|%s' % (ab(a), nb(v))] += 1; r['nc=%s|%s' % (cls(a), nb(v))] += 1
            if a.startswith('W:'): prs.append((a.count('-') + 1, math.log1p(v)))
    r = dict(r)
    if len(prs) >= 3 and np.std([p[0] for p in prs]) > 0 and np.std([p[1] for p in prs]) > 0:
        r['wl_corr'] = float(np.corrcoef(np.array(prs).T)[0, 1])
    return r


def f_long(d):
    c = ctoks(d); W = [t for t in c if t.startswith('W:')]; Ls = [t for t in c if t.startswith('L:')]
    r = Counter()
    if W:
        fs = W[0][2:].split('-')[0]
        for t in c[2:]:
            if t.startswith('W:'): r['h=%s>S%s' % (fs, t[2:].split('-')[0])] += 1
            elif t.startswith('L:'): r['h=%s>%s' % (fs, t)] += 1
        if len(W) >= 2:
            r['hl=%s>%s' % (fs, W[-1][2:].split('-')[0])] += 1
            r['hlw=%s>%s' % (W[0], W[-1])] += 1
            r['same_fs'] = sum(w[2:].split('-')[0] == fs for w in W[1:]) / (len(W) - 1)
            r['same_ls'] = sum(w.split('-')[-1] == W[0].split('-')[-1] for w in W[1:]) / (len(W) - 1)
    if Ls:
        for t in Ls[1:]: r['Lh=%s>%s' % (Ls[0], t)] += 1
        r['nLdist'] = len(set(Ls)); r['Lsame'] = Ls.count(Ls[0]) / len(Ls)
    return dict(r)


def f_rep(d):
    c = ctoks(d); W = [t for t in c if t.startswith('W:')]; L = [l for l in lines_of(d) if l]
    tpl = ['_'.join(cls(t) for t in l) for l in L]
    r = {'wdist': len(set(W)) / max(1, len(W)), 'wmaxrep': max(Counter(W).values()) if W else 0,
         'tokdist': len(set(c)) / len(c),
         'tplsame': sum(a == b for a, b in zip(tpl, tpl[1:])) / max(1, len(tpl) - 1),
         'tpldist': len(set(tpl)) / len(tpl)}
    bg = list(zip(c, c[1:])); r['bgrep'] = 1 - len(set(bg)) / max(1, len(bg))
    for t in set(tpl): r['lt=' + t[:24]] = tpl.count(t)
    return r


GROUPS = {'len': f_len, 'uni': f_uni, 'sign': f_sign, 'sbig': f_sbig, 'tbig': f_tbig, 'pos': f_pos,
          'arith': f_arith, 'numw': f_numw, 'long': f_long, 'rep': f_rep}
ALLG = list(GROUPS) + ['ngram']


def featurize(docs, groups):
    rows = []
    for d in docs:
        r = {}
        for g in groups:
            if g == 'ngram': continue
            for k, v in GROUPS[g](d).items(): r[g + ':' + k] = float(v)
        rows.append(r)
    return rows


def ngram_strings(docs):
    return [' '.join(x.replace(':', '').replace('/', '_') for x in to_stream([ab(t) for t in d])) for d in docs]


